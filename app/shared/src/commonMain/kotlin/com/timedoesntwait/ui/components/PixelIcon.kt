/**
 * An activity's icon: one of the pixel icons by name, or any emoji/text the user typed.
 */
@Composable
fun ActivityIcon(icon: String, modifier: Modifier = Modifier, size: Dp = 24.dp, color: Color = Cobalt.Ink) {
    if (icon in PixelIcons.all) {
        PixelIcon(icon, modifier, size, color)
    } else {
        androidx.compose.foundation.layout.Box(modifier.size(size), contentAlignment = androidx.compose.ui.Alignment.Center) {
            androidx.compose.foundation.text.BasicText(
                icon,
                style = androidx.compose.ui.text.TextStyle(
                    fontSize = androidx.compose.ui.unit.TextUnit(size.value * 0.78f, androidx.compose.ui.unit.TextUnitType.Sp),
                    color = color,
                ),
                maxLines = 1,
            )
        }
    }
}
