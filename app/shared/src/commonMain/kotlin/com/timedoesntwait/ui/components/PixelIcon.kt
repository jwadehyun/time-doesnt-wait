/** 1-bit icons drawn from 12×12 pixel grids, so they match the halftone look exactly. */
@Composable
fun PixelIcon(name: String, modifier: Modifier = Modifier, size: Dp = 24.dp, color: Color = Cobalt.Ink) {
    val grid = PixelIcons.all[name] ?: PixelIcons.all.getValue("star")
    Canvas(modifier.size(size)) {
        val rows = grid.size
        val cols = grid.maxOf { it.length }
        val px = minOf(this.size.width / cols, this.size.height / rows)
        val ox = (this.size.width - px * cols) / 2
        val oy = (this.size.height - px * rows) / 2
        grid.forEachIndexed { y, row ->
            row.forEachIndexed { x, c ->
                if (c == '#') drawRect(color, Offset(ox + x * px, oy + y * px), Size(px + 0.5f, px + 0.5f))
            }
        }
    }
}

